"""Bounded low-reasoning challenger experiment; never a placement decision.

V1's source/crop preparation, prompt, schema and acceptance gate are unchanged.
Only the explicit inference configuration is new. Every attempted response,
including incomplete output and its reported tokens, remains locally retained.
"""
from __future__ import annotations

from copy import deepcopy
import hashlib
import json
from pathlib import Path
import re
from typing import Any, Mapping

from .core import ValidationError
from .meta import MetaAPIError, MetaClient, SPARK_MODEL
from .semantic import (SEMANTIC_VERSION, _hash, challenge_prompt, challenge_schema,
                       _bound_challenge_result, evaluate_challenge, public_challenge_summary,
                       validate_public_challenge_summary, verified_report_usage, verify_prepared)

SEMANTIC_V2_VERSION = "semantic_candidate_v2"
METHOD_CONFIG = {"reasoning_effort": "low", "max_output_tokens": 4096,
                 "max_requests_per_pair": 1, "automatic_retries": 0,
                 "response_schema_name": "proofloop_semantic_candidate_v2"}
_HASH = re.compile(r"^[0-9a-f]{64}$")
_ERROR_CODE = re.compile(r"^[a-z_]{1,64}$")
_LIMIT = ("Completion experiment using the unchanged semantic-v1 prompt, schema and diagnostic gate. "
          "Low reasoning is an explicit request setting, not a reliability guarantee. "
          "Unscored failures never become UNKNOWN predictions or placement decisions. "
          "Reported tokens from unsuccessful responses are included; unreported charges remain unknown.")
_AUTHOR_LIMIT = ("The proposed candidate rectangles were manually authored after source/crop review, "
                 "not generated by a model locator. Spark challenges these proposals using the same semantic gate. "
                 "Candidate support is not independent identity, placement or physical execution proof.")
_REPORT_KEYS = {"method_version", "method_config", "status", "prepared", "request_binding",
                "challenger", "error", "evaluation", "usage"}
_SUMMARY_KEYS = {"method_version", "method_config", "status", "request_binding", "challenge",
                 "failure", "usage", "limitations", "changes_guided_v2_acceptance"}


def verify_prepared_v2(prepared: Mapping[str, Any]) -> None:
    """Dispatch truthful author-reviewed anchors separately from saved locators."""
    if isinstance(prepared, Mapping) and "preparation_version" in prepared:
        from .candidate_review import verify_authored_prepared
        verify_authored_prepared(prepared)
    else:
        verify_prepared(prepared)


def request_binding(prepared: Mapping[str, Any]) -> dict[str, Any]:
    """Exact prompt/schema/source order used by one request; no task answers."""
    return {"prepared_hash": prepared["prepared_hash"], "contract_hash": prepared["contract_hash"],
            "prompt_sha256": hashlib.sha256(challenge_prompt(prepared).encode()).hexdigest(),
            "schema_sha256": _hash(challenge_schema(prepared["contract"])),
            "source_sha256": [frame["sha256"] for frame in prepared["frames"]]
                + [frame["crop_sha256"] for frame in prepared["frames"]]}


def _v1_report(report: Mapping[str, Any]) -> dict[str, Any]:
    return {"method_version": SEMANTIC_VERSION, "prepared": report["prepared"],
            "challenger": report["challenger"], "evaluation": report["evaluation"], "usage": report["usage"]}


def _completed_summary(report: Mapping[str, Any]) -> dict[str, Any]:
    prepared = report["prepared"]
    if "preparation_version" not in prepared:
        return public_challenge_summary(_v1_report(report))
    verify_prepared_v2(prepared)
    _bound_challenge_result(report["challenger"], prepared)
    evaluation = evaluate_challenge(report["challenger"]["parsed"], prepared["contract"])
    if report["evaluation"] != evaluation:
        raise ValidationError("Authored candidate evaluation changed")
    usage = verified_report_usage(_v1_report(report))
    summary = {"method_version": SEMANTIC_VERSION, "preparation_version": prepared["preparation_version"],
               "anchor_origin": "authored_candidate", "author_review": deepcopy(prepared["author_review"]),
               "contract": deepcopy(prepared["contract"]), "contract_hash": prepared["contract_hash"],
               "prepared_hash": prepared["prepared_hash"], "frames": [
                   dict({key: deepcopy(frame[key]) for key in ("frame_index", "sha256", "width", "height",
                         "candidate_box", "crop_box", "crop_sha256")}, assessment=deepcopy(assessment))
                   for frame, assessment in zip(prepared["frames"], evaluation["frames"])],
               "decision": evaluation["decision"], "reasons": evaluation["reasons"], "usage": usage,
               "limitations": _AUTHOR_LIMIT, "changes_guided_v2_acceptance": False}
    _validate_authored_summary(summary)
    return summary


def _validate_authored_summary(summary: Mapping[str, Any]) -> None:
    # Reuse V1's exact source geometry and assessment validator without claiming
    # the authored flags below were observed model outputs. They exist only in
    # this internal validation projection and never enter a report or public DTO.
    keys = {"method_version", "preparation_version", "anchor_origin", "author_review", "contract",
            "contract_hash", "prepared_hash", "frames", "decision", "reasons", "usage", "limitations",
            "changes_guided_v2_acceptance"}
    if (set(summary) != keys or summary["preparation_version"] != "authored_candidate_pair_v1"
            or summary["anchor_origin"] != "authored_candidate" or summary["limitations"] != _AUTHOR_LIMIT):
        raise ValidationError("Invalid public authored candidate provenance")
    review = summary["author_review"]
    if (not isinstance(review, Mapping) or set(review) != {"origin", "source_views_and_crops_reviewed", "note"}
            or review["origin"] != "assistant_under_user_authorization"
            or review["source_views_and_crops_reviewed"] is not True
            or not isinstance(review["note"], str) or not 1 <= len(review["note"].strip()) <= 1500
            or any(ord(char) < 32 for char in review["note"])):
        raise ValidationError("Invalid public authored candidate review")
    from .semantic import _NOTE
    surrogate = {key: deepcopy(value) for key, value in summary.items()
                 if key not in {"preparation_version", "anchor_origin", "author_review"}}
    surrogate["limitations"] = _NOTE
    for frame in surrogate["frames"]:
        if set(frame) != {"frame_index", "sha256", "width", "height", "candidate_box", "crop_box",
                          "crop_sha256", "assessment"}:
            raise ValidationError("Authored public candidate cannot claim locator evidence")
        frame["original_candidate_count"] = 1
        frame["original_locator"] = {"identity_ambiguous": False, "fully_visible": True, "boundary_uncertain": False}
    validate_public_challenge_summary(surrogate)


def challenge_candidate_pair_v2(client: MetaClient, prepared: Mapping[str, Any]) -> dict[str, Any]:
    """Exactly one low-reasoning Spark request; API failures return unscored.

    Preconditions and corrupt source/response bindings raise ValidationError.
    Provider errors retain their raw response locally in ``error.response``.
    There is no retry, inferred answer, or conversion of failure to UNKNOWN.
    """
    if client.retries != 0 or client.max_requests != 1 or client.ledger:
        raise ValidationError("Semantic v2 requires a fresh one-request client with zero retries")
    verify_prepared_v2(prepared)
    report = {"method_version": SEMANTIC_V2_VERSION, "method_config": deepcopy(METHOD_CONFIG),
              "status": "unscored", "prepared": deepcopy(dict(prepared)),
              "request_binding": request_binding(prepared), "challenger": None,
              "error": None, "evaluation": None, "usage": None}
    sources = [Path(frame["source_file"]) for frame in prepared["frames"]]
    crops = [Path(frame["crop_file"]) for frame in prepared["frames"]]
    try:
        result = client.spark_json(challenge_prompt(prepared), challenge_schema(prepared["contract"]),
                                   name=METHOD_CONFIG["response_schema_name"], image_paths=sources + crops,
                                   max_output_tokens=METHOD_CONFIG["max_output_tokens"],
                                   reasoning_effort=METHOD_CONFIG["reasoning_effort"])
    except MetaAPIError as error:
        report["error"] = {"exception_class": "MetaAPIError", "code": error.code,
                           "http_status": error.status, "response": deepcopy(error.response)}
    else:
        report["challenger"] = deepcopy(dict(result))
        try:
            _bound_challenge_result(result, prepared)
            report["evaluation"] = evaluate_challenge(result.get("parsed"), prepared["contract"])
            report["status"] = "completed"
        except ValidationError:
            report["evaluation"] = None
            report["error"] = {"exception_class": "ValidationError", "code": "local_validation_failed",
                               "http_status": None, "response": deepcopy(result.get("response"))}
    report["usage"] = deepcopy(client.usage_summary())
    try:
        verify_prepared_v2(prepared)
    except ValidationError:
        # Keep the paid attempt available to the caller for private retention.
        # Later replay/public export still rejects the changed source evidence.
        report["status"], report["evaluation"] = "unscored", None
        report["error"] = {"exception_class": "ValidationError", "code": "source_evidence_changed",
                           "http_status": None, "response": deepcopy((report["challenger"] or {}).get("response"))}
        return report
    # Replaying immediately uses the same validation as later public export.
    public_challenge_summary_v2(report)
    return report


def _usage(report: Mapping[str, Any]) -> dict[str, Any]:
    saved = report["usage"]
    if not isinstance(saved, Mapping) or not isinstance(saved.get("requests"), list) or len(saved["requests"]) != 1:
        raise ValidationError("Semantic v2 requires its one-request usage ledger")
    entry = saved["requests"][0]
    if (not isinstance(entry, Mapping) or entry.get("endpoint") != "responses"
            or entry.get("model") != SPARK_MODEL or type(entry.get("attempt")) is not int
            or entry["attempt"] != 1 or entry.get("status") not in {
                "ok", "invalid_response", "network_error", "http_error", "invalid_json"}):
        raise ValidationError("Semantic v2 usage ledger has unsupported provenance")
    if "usage" in entry and (not isinstance(entry["usage"], Mapping)
            or any(key in entry["usage"] and (type(entry["usage"][key]) is not int or entry["usage"][key] < 0)
                   for key in ("input_tokens", "output_tokens"))):
        raise ValidationError("Semantic v2 usage tokens are invalid")
    replay = MetaClient("offline-semantic-v2-usage", max_requests=1, retries=0)
    replay.ledger = deepcopy(saved["requests"])
    computed = replay.usage_summary()
    if dict(saved) != computed:
        raise ValidationError("Semantic v2 usage totals differ from the retained request ledger")
    return {key: computed[key] for key in ("request_attempts", "input_tokens", "output_tokens", "estimated_usd")}


def _failure(report: Mapping[str, Any]) -> dict[str, Any]:
    error = report["error"]
    if (report["evaluation"] is not None
            or not isinstance(error, Mapping)
            or set(error) != {"exception_class", "code", "http_status", "response"}
            or error["exception_class"] not in {"MetaAPIError", "ValidationError"}
            or (error["code"] is not None and (not isinstance(error["code"], str)
                                              or not _ERROR_CODE.fullmatch(error["code"])))
            or (error["http_status"] is not None and (type(error["http_status"]) is not int
                                                     or not 100 <= error["http_status"] <= 599))):
        raise ValidationError("Unscored semantic v2 cannot contain an invented assessment")
    entry = report["usage"]["requests"][0]
    response = error["response"]
    if error["exception_class"] == "ValidationError":
        challenger = report["challenger"]
        if (error["code"] != "local_validation_failed" or error["http_status"] is not None
                or not isinstance(challenger, Mapping) or response != challenger.get("response")
                or entry["status"] != "ok"):
            raise ValidationError("Local semantic rejection must retain the actual completed request")
        try:
            _bound_challenge_result(challenger, report["prepared"])
            evaluation = evaluate_challenge(challenger.get("parsed"), report["prepared"]["contract"])
            _completed_summary(dict(report, evaluation=evaluation))
        except ValidationError:
            pass
        else:
            raise ValidationError("A valid semantic assessment cannot be relabeled a local validation failure")
    elif report["challenger"] is not None:
        raise ValidationError("API failure cannot contain an invented challenger result")
    if response is not None:
        if not isinstance(response, Mapping):
            raise ValidationError("Retained semantic API response must be an object")
        if "usage" in response and response["usage"] != entry.get("usage"):
            raise ValidationError("Semantic failure usage differs from the actual response")
        if (error["exception_class"] == "MetaAPIError" and "model" in response
                and response["model"] != SPARK_MODEL):
            raise ValidationError("Semantic failure response belongs to another model")
    if error["exception_class"] == "ValidationError":
        pass  # The failed actual classification/binding was recomputed above.
    elif error["code"] == "incomplete_response":
        if (not isinstance(response, Mapping) or entry["status"] != "invalid_response"
                or response.get("model") != SPARK_MODEL
                or (response.get("status") == "completed" and not response.get("error"))):
            raise ValidationError("Incomplete semantic failure needs its actual rejected response")
    elif entry["status"] == "http_error":
        if error["http_status"] != entry.get("http_status") or error["code"] != entry.get("error_code"):
            raise ValidationError("Semantic HTTP failure differs from the actual request ledger")
    elif error["code"] == "network_error":
        if entry["status"] != "network_error" or response is not None:
            raise ValidationError("Semantic network failure binding changed")
    elif error["code"] == "invalid_json":
        if entry["status"] != "invalid_json" or response is not None:
            raise ValidationError("Semantic invalid JSON failure binding changed")
    elif entry["status"] == "ok":
        # spark_json can reject a completed response after the HTTP ledger is OK.
        if not isinstance(response, Mapping) or response.get("status") != "completed":
            raise ValidationError("Rejected completed semantic output needs its actual response")
        if error["code"] == "schema_validation_failed":
            from .meta import output_text, validate_json
            try:
                validate_json(json.loads(output_text(dict(response))), challenge_schema(report["prepared"]["contract"]))
            except (ValueError, TypeError, KeyError, MetaAPIError):
                pass
            else:
                raise ValidationError("A valid structured answer cannot be relabeled as a schema failure")
    return {"code": error["code"], "http_status": error["http_status"],
            "response_status": response.get("status") if isinstance(response, Mapping) else None,
            "raw_response_retained": response is not None,
            "token_usage_reported": all(type(entry.get("usage", {}).get(key)) is int
                                        for key in ("input_tokens", "output_tokens")),
            "scored": False}


def public_challenge_summary_v2(report: Mapping[str, Any]) -> dict[str, Any]:
    """Reverify private evidence and recompute the entire public safe DTO."""
    try:
        if (not isinstance(report, Mapping) or set(report) != _REPORT_KEYS
                or report["method_version"] != SEMANTIC_V2_VERSION
                or report["method_config"] != METHOD_CONFIG):
            raise ValidationError("Semantic v2 method configuration changed")
        verify_prepared_v2(report["prepared"])
        if report["request_binding"] != request_binding(report["prepared"]):
            raise ValidationError("Semantic v2 request source/prompt/schema binding changed")
        usage = _usage(report)
        challenge = failure = None
        if report["status"] == "completed":
            if report["error"] is not None:
                raise ValidationError("Completed semantic v2 cannot hide a request failure")
            challenge = _completed_summary(report)
        elif report["status"] == "unscored":
            failure = _failure(report)
        else:
            raise ValidationError("Unsupported semantic v2 attempt status")
        summary = {"method_version": SEMANTIC_V2_VERSION, "method_config": deepcopy(METHOD_CONFIG),
                   "status": report["status"], "request_binding": deepcopy(report["request_binding"]),
                   "challenge": challenge, "failure": failure, "usage": usage,
                   "limitations": _LIMIT, "changes_guided_v2_acceptance": False}
        validate_public_challenge_summary_v2(summary)
        return summary
    except (KeyError, TypeError, ValueError):
        raise ValidationError("Invalid retained semantic v2 attempt") from None


def validate_public_challenge_summary_v2(summary: Any) -> None:
    """Validate public shape without pretending public hashes prove API origin."""
    try:
        if (not isinstance(summary, Mapping) or set(summary) != _SUMMARY_KEYS
                or summary["method_version"] != SEMANTIC_V2_VERSION
                or summary["method_config"] != METHOD_CONFIG or summary["limitations"] != _LIMIT
                or summary["changes_guided_v2_acceptance"] is not False):
            raise ValidationError("Invalid public semantic v2 shape")
        binding = summary["request_binding"]
        if (not isinstance(binding, Mapping) or set(binding) != {
                "prepared_hash", "contract_hash", "prompt_sha256", "schema_sha256", "source_sha256"}
                or any(not isinstance(binding[key], str) or not _HASH.fullmatch(binding[key])
                       for key in ("prepared_hash", "contract_hash", "prompt_sha256", "schema_sha256"))
                or not isinstance(binding["source_sha256"], list) or len(binding["source_sha256"]) != 4
                or any(not isinstance(value, str) or not _HASH.fullmatch(value) for value in binding["source_sha256"])):
            raise ValidationError("Invalid public semantic v2 request binding")
        if summary["status"] == "completed":
            if summary["failure"] is not None:
                raise ValidationError("Completed semantic v2 contains a failure")
            challenge = summary["challenge"]
            if isinstance(challenge, Mapping) and "preparation_version" in challenge:
                _validate_authored_summary(challenge)
            else:
                validate_public_challenge_summary(challenge)
            if (challenge["prepared_hash"] != binding["prepared_hash"]
                    or challenge["contract_hash"] != binding["contract_hash"]
                    or challenge["usage"] != summary["usage"]
                    or binding["source_sha256"] != [frame["sha256"] for frame in challenge["frames"]]
                        + [frame["crop_sha256"] for frame in challenge["frames"]]):
                raise ValidationError("Public semantic v2 source or usage binding changed")
        elif summary["status"] == "unscored":
            failure = summary["failure"]
            if (summary["challenge"] is not None or not isinstance(failure, Mapping)
                    or set(failure) != {"code", "http_status", "response_status", "raw_response_retained",
                                        "token_usage_reported", "scored"}
                    or failure["scored"] is not False
                    or any(type(failure[key]) is not bool for key in ("raw_response_retained", "token_usage_reported"))
                    or (failure["code"] is not None and (not isinstance(failure["code"], str)
                                                         or not _ERROR_CODE.fullmatch(failure["code"])))
                    or (failure["http_status"] is not None and (type(failure["http_status"]) is not int
                                                               or not 100 <= failure["http_status"] <= 599))
                    or (failure["response_status"] is not None and failure["response_status"] not in {
                        "completed", "incomplete", "failed", "cancelled", "queued", "in_progress"})):
                raise ValidationError("Invalid public unscored semantic v2 failure")
        else:
            raise ValidationError("Unknown public semantic v2 status")
        usage = summary["usage"]
        if (not isinstance(usage, Mapping) or set(usage) != {"request_attempts", "input_tokens", "output_tokens", "estimated_usd"}
                or type(usage["request_attempts"]) is not int or usage["request_attempts"] != 1
                or any(type(usage[key]) is not int or usage[key] < 0 for key in ("input_tokens", "output_tokens"))
                or type(usage["estimated_usd"]) not in (int, float) or not 0 <= usage["estimated_usd"] <= 10):
            raise ValidationError("Invalid public semantic v2 usage")
    except (KeyError, TypeError, ValueError):
        raise ValidationError("Invalid public semantic v2 fields") from None
