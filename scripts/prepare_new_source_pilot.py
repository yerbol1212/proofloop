class PreparationError(ValueError):
    pass


def sha256(data):
    return hashlib.sha256(data).hexdigest()


def encoded(value):
    return (json.dumps(value, sort_keys=True, separators=(",", ":"), allow_nan=False) + "\n").encode()


def checked_bytes(data, expected_bytes, expected_hash):
    if (type(expected_bytes) is not int or expected_bytes <= 0 or type(data) is not bytes
            or len(data) != expected_bytes or sha256(data) != expected_hash):
        raise PreparationError("Pinned download bytes or SHA-256 differ")
    return data


def _https(url):
    parsed = urlparse(url)
    host = parsed.hostname or ""
    if (parsed.scheme != "https" or parsed.username or parsed.password or parsed.port not in (None, 443)
            or not (host == "huggingface.co" or host.endswith(".huggingface.co") or host.endswith(".hf.co"))):
        raise PreparationError("Only HTTPS Hugging Face/CDN downloads are supported")


class BoundedRedirects(HTTPRedirectHandler):
    def __init__(self):
        super().__init__()
        self.redirects = 0

    def redirect_request(self, req, fp, code, msg, headers, newurl):
        self.redirects += 1
        if self.redirects > 4:
            raise PreparationError("Download redirect allowance exceeded")
        _https(newurl)
        return super().redirect_request(req, fp, code, msg, headers, newurl)


def bounded_read(response, limit, deadline, *, first_line=False, clock=time.monotonic):
    if type(limit) is not int or not 0 < limit <= 8 * 1024 * 1024:
        raise PreparationError("Download limit is invalid")
    if clock() >= deadline:
        raise PreparationError("Preparation time allowance exhausted")
    if first_line:
        data = response.readline(limit + 1)
    else:
        chunks, size = [], 0
        while True:
            if clock() >= deadline:
                raise PreparationError("Preparation time allowance exhausted")
            chunk = response.read(min(65536, limit + 1 - size))
            if not chunk:
                break
            chunks.append(chunk)
            size += len(chunk)
            if size > limit:
                raise PreparationError("Download byte allowance exceeded")
        data = b"".join(chunks)
    if clock() >= deadline or not 0 < len(data) <= limit:
        raise PreparationError("Download is empty, excessive or timed out")
    return data


def download(url, limit, deadline, *, first_line=False):
    _https(url)
    remaining = deadline - time.monotonic()
    if remaining <= 0:
        raise PreparationError("Preparation time allowance exhausted")
    request = Request(url, headers={"User-Agent": "ProofLoop-source-reproduction/1.0", "Accept-Encoding": "identity"})
    with build_opener(BoundedRedirects()).open(request, timeout=min(10, remaining)) as response:
        _https(response.url)
        return bounded_read(response, limit, deadline, first_line=first_line)


def run_tool(command, *, timeout=MAX_TOOL_SECONDS, limit=MAX_TOOL_BYTES):
    """Bound both process duration and captured output without shell execution."""
    started = time.monotonic()
    with tempfile.TemporaryFile() as stdout, tempfile.TemporaryFile() as stderr:
        process = subprocess.Popen(command, stdin=subprocess.DEVNULL, stdout=stdout, stderr=stderr)
        try:
            while True:
                if time.monotonic() - started >= timeout:
                    raise PreparationError("Media tool exceeded its time allowance")
                if any(os.fstat(stream.fileno()).st_size > limit for stream in (stdout, stderr)):
                    raise PreparationError("Media tool exceeded its output allowance")
                try:
                    process.wait(timeout=min(.1, max(.001, timeout - (time.monotonic() - started))))
                    break
                except subprocess.TimeoutExpired:
                    pass
            if process.returncode != 0:
                raise PreparationError("Media tool failed; no completed preparation receipt issued")
            stdout.seek(0)
            data = stdout.read(limit + 1)
            if len(data) > limit or os.fstat(stderr.fileno()).st_size > limit:
                raise PreparationError("Media tool exceeded its output allowance")
            return data
        finally:
            if process.poll() is None:
                process.kill()
            process.wait()


def discover_tools(root=ROOT):
    result = {}
    for name in ("ffmpeg", "ffprobe"):
        local = Path(root) / ".venv/bin" / name
        candidate = str(local) if local.is_file() and os.access(local, os.X_OK) else shutil.which(name)
        if not candidate:
            raise PreparationError("FFmpeg and ffprobe must be installed before downloading")
        result[name] = candidate
    return result


def private_destination(output, root=ROOT):
    root = Path(root).resolve()
    path = Path(output)
    if not path.is_absolute():
        path = root / path
    allowed = root / "inputs/local"
    # Reject symlink aliases, including aliases that happen to resolve inside.
    if any(parent.is_symlink() for parent in (path, *path.parents) if parent != root.parent):
        raise PreparationError("Preparation paths must not contain symlinks")
    destination = path.resolve()
    if allowed.resolve() not in destination.parents or destination == allowed.resolve():
        raise PreparationError("Use a new directory strictly inside this checkout's inputs/local")
    if destination.exists():
        raise PreparationError("Output already exists; existing experiment files are never overwritten")
    return destination


def write_new(path, data):
    descriptor = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(descriptor, "wb") as stream:
        stream.write(data)
        stream.flush()
        os.fsync(stream.fileno())


def _milliseconds(value):
    try:
        number = Decimal(str(value))
        if not number.is_finite():
            raise InvalidOperation
        return int((number * 1000).to_integral_value(rounding=ROUND_HALF_EVEN))
    except (InvalidOperation, ValueError, OverflowError):
        raise PreparationError("Timestamp must be finite") from None


def timing_mapping(source, probe, metadata=None):
    """Bind decoder indices/PTS to capture time without treating playback as it."""
    try:
        stream, = probe["streams"]
        frames = probe["frames"]
        duration = _milliseconds(probe["format"]["duration"])
        time_base = Fraction(stream["time_base"])
        if (stream["width"] != 640 or stream["height"] != 480 or not 0 < time_base <= 1
                or type(frames) is not list or len(frames) != source.frame_count or not 0 < duration <= 120000
                or int(stream.get("tags", {}).get("rotate", 0)) != 0
                or any(item.get("rotation", 0) != 0 for item in stream.get("side_data_list", []))):
            raise PreparationError("Decoded source dimensions, timing or frame inventory differ")
        result = []
        for index, frame in enumerate(frames):
            pts = frame["best_effort_timestamp"]
            if (type(pts) is not int or pts < 0 or frame.get("media_type") != "video"
                    or frame["width"] != 640 or frame["height"] != 480):
                raise PreparationError("Invalid decoded frame/PTS mapping")
            exact_seconds = Decimal(pts * time_base.numerator) / Decimal(time_base.denominator)
            reported_seconds = Decimal(frame["best_effort_timestamp_time"])
            if not reported_seconds.is_finite() or abs(exact_seconds - reported_seconds) > Decimal("0.000001"):
                raise PreparationError("Encoded PTS and its presentation time disagree")
            result.append({"decoded_frame_index": index, "encoded_pts": pts,
                "encoded_time_base": str(stream["time_base"]),
                "encoded_pts_time": str(frame["best_effort_timestamp_time"]),
                "encoded_pts_ms": _milliseconds(exact_seconds)})
        encoded_times = [item["encoded_pts_ms"] for item in result]
        if encoded_times[0] != 0 or any(b <= a for a, b in zip(encoded_times, encoded_times[1:])) or encoded_times[-1] >= duration:
            raise PreparationError("Encoded presentation timeline must be ordered and start at zero")
        if source.id == "bridge-scripted-0":
            if metadata is None:
                raise PreparationError("Bridge requires its pinned capture metadata; 1 fps playback is not capture time")
            row = json.loads(metadata, parse_float=Decimal)
            capture = row["observation_data"]["time_stamp"]
            if row["file_name"] != METADATA_FILENAME or row["num_frames"] != len(result) or len(capture) != len(result):
                raise PreparationError("Bridge capture metadata does not match the exact video inventory")
            values = []
            for value in capture:
                if isinstance(value, list):
                    if len(value) != 1:
                        raise PreparationError("Bridge capture timestamp has an unsupported shape")
                    value = value[0]
                if isinstance(value, bool):
                    raise PreparationError("Bridge capture timestamps must be numeric")
                number = Decimal(str(value))
                if not number.is_finite():
                    raise PreparationError("Bridge capture timestamps must be finite")
                values.append(number)
            for item, value in zip(result, values):
                item.update(capture_timestamp_seconds=str(value), source_timestamp_ms=_milliseconds(value - values[0]))
            basis = "original_dataset_capture_timestamps"
        else:
            for item in result:
                item["source_timestamp_ms"] = item["encoded_pts_ms"]
            basis = "decoded_video_presentation_timestamps"
        times = [item["source_timestamp_ms"] for item in result]
        if times[0] != 0 or times[-1] > 120000 or any(b <= a for a, b in zip(times, times[1:])):
            raise PreparationError("Source timeline must be finite, strictly increasing and bounded")
        return basis, result, duration
    except (KeyError, TypeError, ValueError, InvalidOperation, ZeroDivisionError) as error:
        if isinstance(error, PreparationError):
            raise
        raise PreparationError("Invalid source timing metadata") from None


def select_pairs(times):
    if (not isinstance(times, list) or len(times) < 6 or any(type(value) is not int or value < 0 for value in times)
            or times[0] != 0 or any(b <= a for a, b in zip(times, times[1:]))):
        raise PreparationError("Pair sampling needs an ordered zero-based source timeline")
    last = times[-1]
    starts = [0, min(range(len(times)), key=lambda i: abs(2 * times[i] - (last - 1000))),
              max((i for i, value in enumerate(times) if value <= last - 1000), default=-1)]
    pairs, seen = [], set()
    for start in starts:
        end = next((i for i, value in enumerate(times) if value >= times[start] + 1000), None)
        if (start < 0 or end is None or start in seen or end in seen
                or pairs and start <= pairs[-1][1]):
            raise PreparationError("Fixed sampling cannot provide three nonoverlapping distinct one-second pairs")
        pairs.append((start, end))
        seen.update((start, end))
    return pairs


def prepare(output, *, root=ROOT, sources=SOURCES, fetch=download, runner=run_tool, tools=None, clock=time.monotonic):
    destination = private_destination(output, root)
    if (not 1 <= len(sources) <= 3 or len({source.id for source in sources}) != len(sources)
            or any(source.id not in {item.id for item in SOURCES}
                   or type(source.bytes) is not int or not 0 < source.bytes <= 8 * 1024 * 1024
                   or type(source.card_bytes) is not int or not 0 < source.card_bytes <= 262144
                   or type(source.frame_count) is not int or not 6 <= source.frame_count <= 600
                   or re.fullmatch(r"[0-9a-f]{64}", source.sha256) is None
                   or re.fullmatch(r"[0-9a-f]{64}", source.card_sha256) is None for source in sources)):
        raise PreparationError("Source inventory is invalid")
    for source in sources:
        _https(source.url)
        _https(source.card_url)
    tools = tools or discover_tools(root)
    deadline = clock() + MAX_DOWNLOAD_SECONDS
    def tool(command):
        remaining = deadline - clock()
        if remaining <= 0:
            raise PreparationError("Preparation time allowance exhausted")
        return runner(command, timeout=min(MAX_TOOL_SECONDS, remaining), limit=MAX_TOOL_BYTES)
    versions = {}
    for name in ("ffmpeg", "ffprobe"):
        lines = tool([tools[name], "-version"]).decode("utf-8").splitlines()
        if not lines or not lines[0].startswith(name + " version "):
            raise PreparationError("Unexpected media tool identity")
        versions[name] = lines[0][:300]
    destination.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
    destination.mkdir(mode=0o700)  # Atomic reservation: never adopt an existing directory.
    records, cached = [], {}
    def obtain(url, size, digest, *, first_line=False):
        key = (url, digest)
        if key not in cached:
            cached[key] = checked_bytes(fetch(url, size, deadline, first_line=first_line), size, digest)
        return cached[key]
    for source in sources:
        video = destination / (source.id + ".mp4")
        write_new(video, obtain(source.url, source.bytes, source.sha256))
        card = obtain(source.card_url, source.card_bytes, source.card_sha256)
        card.decode("utf-8")
        write_new(destination / (source.id + "-card.md"), card)
        metadata = None
        if source.id == "bridge-scripted-0":
            metadata = obtain(METADATA_URL, METADATA_BYTES, METADATA_SHA256, first_line=True)
            write_new(destination / (source.id + "-metadata-row.json"), metadata)
        probe_bytes = tool([tools["ffprobe"], "-v", "error", "-show_streams", "-show_format", "-show_frames",
                            "-select_streams", "v:0", "-of", "json", str(video)])
        probe = json.loads(probe_bytes)
        basis, mapping, encoded_duration = timing_mapping(source, probe, metadata)
        write_new(destination / (source.id + "-probe.json"), probe_bytes)
        mapping_hash = sha256(encoded(mapping))
        pairs = []
        for number, pair in enumerate(select_pairs([row["source_timestamp_ms"] for row in mapping])):
            selected = []
            for index in pair:
                frame = destination / f"{source.id}-frame-{index:03d}.jpg"
                tool([tools["ffmpeg"], "-nostdin", "-n", "-v", "error", "-noautorotate", "-i", str(video),
                      "-vf", "select=eq(n\\," + str(index) + ")", "-fps_mode", "passthrough", "-frames:v", "1",
                      "-q:v", "2", "-map_metadata", "-1", str(frame)])
                if frame.is_symlink() or not frame.is_file() or not 4 <= frame.stat().st_size <= MAX_JPEG_BYTES:
                    raise PreparationError("Decoded JPEG is unavailable or excessive")
                data = frame.read_bytes()
                if not data.startswith(b"\xff\xd8") or not data.endswith(b"\xff\xd9"):
                    raise PreparationError("Media tool did not produce a JPEG")
                frame.chmod(0o600)
                selected.append({**mapping[index], "file": frame.relative_to(Path(root).resolve()).as_posix(),
                    "sha256": sha256(data), "source_sha256": source.sha256, "timing_mapping_sha256": mapping_hash,
                    "transform": "Original decoded frame to JPEG; no crop, resize, rotation or generated content"})
            pairs.append({"index": number, "frames": selected})
        record = {"schema_version": "prospective_source_preparation_v1", "source_id": source.id,
            "source": asdict(source), "time_basis": basis, "capture_metadata_row_sha256": sha256(metadata) if metadata else None,
            "probe_sha256": sha256(probe_bytes), "timing_mapping": mapping, "timing_mapping_sha256": mapping_hash,
            "duration_ms": mapping[-1]["source_timestamp_ms"] + 1, "encoded_duration_ms": encoded_duration,
            "sampling": SAMPLING, "pairs": pairs, "tools": versions, "provider_requests": 0, "limitations": LIMITATIONS}
        record["receipt_sha256"] = sha256(encoded(record))
        write_new(destination / (source.id + "-prepared.json"), encoded(record))
        records.append({"source_id": source.id, "receipt_sha256": record["receipt_sha256"],
                        "pairs": [[frame["decoded_frame_index"] for frame in pair["frames"]] for pair in pairs]})
    report = {"schema_version": "prospective_source_preparation_run_v1", "provider_requests": 0,
              "sources": records, "sampling": SAMPLING, "limitations": LIMITATIONS}
    write_new(destination / "preparation-complete.json", encoded(report))
    return report


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--download", action="store_true", help="Explicitly download and prepare the pinned sources; no Meta calls")
    parser.add_argument("--output", type=Path, default=Path(DEFAULT_OUTPUT), help="New directory strictly inside inputs/local; never overwritten")
    args = parser.parse_args(argv)
    plan = {"mode": "plan_only", "network_requests": 0, "provider_requests": 0, "writes": False,
            "output": str(args.output), "sources": [asdict(source) for source in SOURCES],
            "bridge_capture_metadata": {"url": METADATA_URL, "first_row_bytes": METADATA_BYTES, "sha256": METADATA_SHA256},
            "sampling": SAMPLING, "limitations": LIMITATIONS}
    if not args.download:
        print(json.dumps(plan, indent=2, allow_nan=False))
        return 0
    try:
        report = prepare(args.output)
    except (OSError, ValueError, UnicodeError, KeyError, TypeError, subprocess.SubprocessError):
        print("Source preparation failed. No approval or inference ran. Existing files were not overwritten; incomplete new output has no preparation-complete receipt.", file=sys.stderr)
        return 1
    print(json.dumps(report, indent=2, allow_nan=False))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
